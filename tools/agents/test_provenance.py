def grace_provenance(media, out):
    """The exact block added to _grace()."""
    defects, checked = [], []
    vdir = Path(media).parent
    plan_json = vdir / "video_plan.json"
    wan_clips = sorted(vdir.glob("clip*.mp4"))
    gen_log = ""
    for cand in (vdir / "videogen_real.log", vdir / "video.log"):
        if cand.exists():
            gen_log = cand.read_text(encoding="utf-8", errors="replace")
            break
    real_gen = bool(plan_json.exists() and wan_clips) or "Wan" in gen_log
    if real_gen:
        checked.append("generated by Wan2.1 (video_plan.json + %d scene clip(s))" % len(wan_clips))
    else:
        defects.append("NOT generated scene-by-scene ... Ken Burns")
    m = V.motion_metrics(media)
    if m:
        checked.append("motion profile (informational): mean %.2f static %.2f"
                       % (m["mean"], m["static_frac"]))
    return defects, checked, real_gen


